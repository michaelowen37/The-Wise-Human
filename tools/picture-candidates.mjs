// Picture candidates (pass JV, Mikey: the lesson that says a slice of pizza is almost a triangle would teach better with the
// slice beside the triangle). In plain terms: lists every early-years lesson line, pre-K to grade 2, that compares an idea
// to a real thing (like a, almost a, looks like, shaped like) and has no lesson picture of its own yet. Each row is a place
// where seeing the real thing beside the idea may teach more than the words. The full standard reads these rows for every
// module it reviews (docs/FABLE-REVIEW.md): draw the pair now when the app can, and log a P painting for Leonardo.
// Run: node tools/picture-candidates.mjs > docs/PICTURE-CANDIDATES.md
import * as L from '../src/logic.mjs';

const EARLY = ['PK3', 'PK4', 'K', '1', '2'];
// "like a strawberry", "almost a triangle", "looks like the moon"; "like this" and "I like it" are not comparisons.
const COMPARE = /\b(?:just like|looks like|shaped like|like|almost)\s+(?:a|an|the|two|some)\s+[a-z]+(?:\s+[a-z]+)?/gi;
const rows = [];
for (const c of L.COURSES.filter((x) => EARLY.includes(x.grade))) {
  for (const m of c.modules) {
    const lines = c.readAloud ? L.readAloudScript(m).map((s) => s.say) : (m.lesson.paragraphs || []);
    const steps = new Set((m.lesson.pictures || []).map((p) => p.step));
    lines.forEach((text, i) => {
      const hits = [...String(text).matchAll(COMPARE)].map((x) => x[0]);
      if (!hits.length) return;
      const pictured = c.readAloud ? steps.has(i) : steps.size > 0;
      rows.push({ grade: c.grade, course: c.title, module: m.title, id: m.id, line: i, hits, text, pictured });
    });
  }
}
const open = rows.filter((r) => !r.pictured);
const cell = (s) => String(s).replace(/\|/g, '/');
console.log('# Picture candidates');
console.log('');
console.log(`Generated by tools/picture-candidates.mjs. ${open.length} early-years lesson lines compare an idea to a real thing and have no lesson picture yet; ${rows.length - open.length} already have one. A row is a question, not a verdict: show the real thing beside the idea where seeing it teaches more than the words (a drawn pair now when the app can draw it, and a P painting logged in docs/ART-REQUESTS.md). Mikey's example is the pizza slice beside the triangle in pre-K 3 Triangles (pass JV).`);
console.log('');
console.log('| Grade | Course | Module | Line | Comparison | Words |');
console.log('|---|---|---|---|---|---|');
for (const r of open) console.log(`| ${r.grade} | ${cell(r.course)} | ${cell(r.module)} (\`${r.id}\`) | ${r.line} | ${cell(r.hits.join('; '))} | ${cell(r.text)} |`);
